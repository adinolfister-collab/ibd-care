// Shared backend i18n: resolve the user's language server-side and provide
// IT/EN dictionaries for the 5 localized backend functions (therapy reminders,
// evening meal check, dormant reminders, support reply, medical report).
// The frontend persists `lang` on the User entity via base44.auth.updateMe;
// backends read it here with a robust fallback to Italian.

const SUPPORTED = ['it', 'en'] as const;
export type Lang = (typeof SUPPORTED)[number];

export function resolveLang(lang: string | null | undefined): Lang {
  return (SUPPORTED as readonly string[]).includes(String(lang)) ? (lang as Lang) : 'it';
}

// Read lang from an already-fetched user object (no extra DB call).
export function langOf(user: { lang?: string } | null | undefined): Lang {
  return resolveLang(user?.lang);
}

// Fetch lang by user id (service role). Used by scheduled/workflow functions
// that iterate over users and only have the id.
export async function getLang(base44: any, userId: string): Promise<Lang> {
  try {
    const u = await base44.asServiceRole.entities.User.get(userId);
    return langOf(u);
  } catch {
    return 'it';
  }
}

// Fetch lang by email (service role). Used by replySupportTicket where the
// ticket author may be a guest (created_by_id empty) but their email is known.
export async function getLangByEmail(base44: any, email: string): Promise<Lang> {
  try {
    const found = await base44.asServiceRole.entities.User.filter({ email }, '-created_date', 1);
    return langOf(found && found[0]);
  } catch {
    return 'it';
  }
}

